package llm

import "context"

type Role string

const (
	RoleUser      Role = "user"
	RoleAssistant Role = "assistant"
)

type Message struct {
	Role    Role
	Content string
	ToolCalls  []ToolCall  // set on an assistant message that asks for tools
	ToolResult *ToolResult // set on a RoleTool message that answers one 
}

type Usage struct {
	InputTokens  int
	OutputTokens int
}

type Provider interface {
	// Chat sends a chat request to the LLM with the provided history and system prompt, returning the final response, usage statistics, and any error encountered.
	Chat(ctx context.Context, history []Message, systemPrompt string) (string, Usage, error)
	// ChatStream streams the response from the LLM, calling onChunk for each chunk of text received. It returns the final response, usage statistics, and any error encountered.
	ChatStream(ctx context.Context, history []Message, systemPrompt string, onChunk func(string)) (string, Usage, error)
	// ChatJSON sends a JSON-formatted chat request to the LLM with the provided history, system prompt, and response schema, returning the final response, usage statistics, and any error encountered.
	ChatJSON(ctx context.Context, history []Message, systemPrompt string, schema map[string]any) (string, Usage, error)
	// ChatTools sends a chat request to the LLM with the provided history, system prompt, and available tools, returning the final response, usage statistics, and any error encountered.
	ChatTools(ctx context.Context, history []Message, systemPrompt string, tools []ToolSpec) (Reply, Usage, error)
}

// tool role is used for messages generated by tools or external systems, allowing the LLM to differentiate between user input, assistant responses, and tool-generated content.
const RoleTool Role = "tool"

// ToolSpec describes a tool the model may ask for.
type ToolSpec struct {
	Name        string
	Description string
	Parameters  map[string]any // schema for the arguments, same style as taskSchema
}

// ToolCall is the model asking you to run a tool.
type ToolCall struct {
	Name   string
	Args   map[string]any
	Opaque string // provider data to send back unchanged (Gemini's thought signature)
}

// ToolResult is what your code sends back after running a tool.
type ToolResult struct {
	Name   string
	Result map[string]any
}

// Reply is what a tools-enabled call returns: text, or tool requests, or both.
type Reply struct {
	Text      string
	ToolCalls []ToolCall
}

